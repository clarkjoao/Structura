import { describe, expect, it } from "vitest";
import type { Component, Connection, Diagram, NodeLayout } from "@/features/diagram";
import "@/features/elements/bootstrap";
import { fixture } from "./__fixtures__/load";
import { exportDrawio } from "./export-drawio";
import { parseDrawioXml } from "./import-drawio";

/**
 * File-based draw.io fixtures (see __fixtures__/drawio). The .drawio files were produced by
 * exportDrawio itself; desktop-compressed.drawio is the same model deflated like draw.io
 * desktop does by default.
 */

const FILES = ["desktop-uncompressed", "containers-relative", "vertical-waypoints"] as const;

const origin = { x: 0, y: 0 };
const importFile = (name: string) => parseDrawioXml(fixture(`drawio/${name}.drawio`), origin, {});

const names = (components: Component[]) => components.map((c) => c.name).sort();
const byName = (components: Component[]) => Object.fromEntries(components.map((c) => [c.name, c]));
const edgePairs = (r: { components: Component[]; connections: Connection[] }) =>
  r.connections
    .map((c) => {
      const label = c.label ?? "";
      const from = r.components.find((x) => x.id === c.sourceId)?.name;
      const to = r.components.find((x) => x.id === c.targetId)?.name;
      return `${from}->${to}:${label}`;
    })
    .sort();

/** Rebuilds a Diagram from an import result so it can be exported again. */
function diagramFrom(r: ReturnType<typeof importFile>): Diagram {
  const components: Record<string, Component> = {};
  r.components.forEach((c) => (components[c.id] = c));
  const connections: Record<string, Connection> = {};
  r.connections.forEach((c) => (connections[c.id] = c));
  const nodeLayouts: Record<string, NodeLayout> = {};
  r.layouts.forEach((l) => (nodeLayouts[l.elementId] = l));
  return {
    id: "rt",
    name: "Round trip",
    level: "context",
    createdAt: 0,
    updatedAt: 0,
    snapshot: { components, connections, flows: {}, iconLibrary: {} },
    nodeLayouts,
    edgeLayouts: {},
    viewport: { x: 0, y: 0, zoom: 1 },
  };
}

describe("draw.io fixtures: import -> export -> import is stable", () => {
  it.each(FILES)("%s keeps labels, parent/child, edges and cloudServiceId", (file) => {
    const first = importFile(file);
    expect(first.components.length).toBeGreaterThan(0);

    const second = parseDrawioXml(exportDrawio(diagramFrom(first), {}), origin, {});

    expect(names(second.components)).toEqual(names(first.components));
    expect(edgePairs(second)).toEqual(edgePairs(first));
    // Ids are regenerated by the importer, so compare the parent relation by name.
    const parentName = (r: typeof first) =>
      Object.fromEntries(
        r.components.map((c) => [c.name, r.components.find((p) => p.id === c.parentId)?.name]),
      );
    expect(parentName(second)).toEqual(parentName(first));
    const cloud = (r: typeof first) =>
      Object.fromEntries(
        r.components.map((c) => [c.name, (c as { cloudServiceId?: string }).cloudServiceId]),
      );
    expect(cloud(second)).toEqual(cloud(first));
  });

  it("containers fixture: children stay inside their panel", () => {
    const r = importFile("containers-relative");
    const comps = byName(r.components);
    expect(names(r.components)).toEqual(["Service A", "Service B", "VPC"]);
    expect(comps["Service A"]!.parentId).toBe(comps.VPC!.id);
    expect(comps["Service B"]!.parentId).toBe(comps.VPC!.id);
  });

  // 49416c0b: cloud families emit cloudServiceId in the mxGraph XML.
  it("cloud fixture exported from code carries cloudServiceId for every family", () => {
    const xml = fixture("drawio/cloud-service-id.drawio");
    for (const id of ["lambda", "cloudrun", "functions"]) {
      expect(xml).toContain(`cloudServiceId="${id}"`);
    }
  });

  // 49416c0b: the identity of a draw.io-native AWS icon survives import and the next export.
  it("aws-native fixture: prIcon becomes cloudServiceId and is emitted again", () => {
    const first = importFile("aws-native");
    const fn = first.components.find((c) => c.name === "Orders function") as
      { cloudServiceId?: string } | undefined;
    expect(fn?.cloudServiceId).toBe("lambda");
    const xml = exportDrawio(diagramFrom(first), {});
    expect(xml).toContain('cloudServiceId="lambda"');
    expect(xml).toContain('cloudServiceId="s3"');
  });

  // Since 49416c0b an AWS node with a cloudServiceId is exported as
  // <object id cloudServiceId><mxCell/></object>: the id lives on the wrapper (RT-035).
  it("re-imports an AWS node that Structura exported with cloudServiceId", () => {
    const first = importFile("aws-native");
    const r = parseDrawioXml(exportDrawio(diagramFrom(first), {}), origin, {});
    const lambda = r.components.find((c) => c.name === "Orders function") as
      { cloudServiceId?: string } | undefined;
    expect(lambda?.cloudServiceId).toBe("lambda");
  });

  it("reads wrapped <object>/<UserObject> vertices and edges generally", () => {
    const cell = (extra: string, geom = "") => `<mxCell ${extra}>${geom}</mxCell>`;
    const xml =
      `<mxGraphModel><root><mxCell id="0"/><mxCell id="1" parent="0"/>` +
      `<object label="A" id="a" owner="x">${cell('style="shape=mxgraph.aws4.productIcon;prIcon=mxgraph.aws4.s3;" vertex="1" parent="1"', '<mxGeometry x="0" y="0" width="60" height="60" as="geometry"/>')}</object>` +
      `<UserObject label="B" id="b">${cell('style="shape=mxgraph.aws4.productIcon;prIcon=mxgraph.aws4.lambda;" vertex="1" parent="1"', '<mxGeometry x="200" y="0" width="60" height="60" as="geometry"/>')}</UserObject>` +
      `<object label="calls" id="e">${cell('edge="1" source="a" target="b" parent="1"')}</object>` +
      `</root></mxGraphModel>`;
    const r = parseDrawioXml(xml, origin, {});
    expect(names(r.components)).toEqual(["A", "B"]);
    expect(r.connections).toHaveLength(1);
    expect(r.connections[0]!.label).toBe("calls");
    expect(r.skipped).toEqual([]);
  });

  it("not XML at all imports as nothing instead of throwing", () => {
    expect(parseDrawioXml("<<<not xml", origin, {}).components).toEqual([]);
  });

  // Gap found while building the corpus: draw.io desktop compresses <diagram> by default
  // (deflate-raw + base64 + URI-encoding). The importer only reads the inline mxGraphModel, so
  // a default draw.io desktop file imports as an empty diagram.
  it.fails("imports a draw.io desktop file whose <diagram> is compressed", () => {
    const r = importFile("desktop-uncompressed");
    const compressed = parseDrawioXml(fixture("drawio/desktop-compressed.drawio"), origin, {});
    expect(names(compressed.components)).toEqual(names(r.components));
  });
});

describe("draw.io export of the vertical-flow fixture", () => {
  // d35b7121: geometry-inferred anchors and orthogonal routing for vertical flows.
  it("routes orthogonally and keeps the stored waypoints as mxPoints", () => {
    const xml = fixture("drawio/vertical-waypoints.drawio");
    expect(xml).toContain("edgeStyle=orthogonalEdgeStyle");
    const points = [...xml.matchAll(/<mxPoint x="([^"]+)" y="([^"]+)"\/>/g)];
    expect(points).toHaveLength(2);
  });

  it("a stacked pair with no waypoints leaves from the bottom and enters at the top", () => {
    const components: Record<string, Component> = {
      top: { id: "top", name: "Top", type: "system", description: "", parentId: null },
      bot: { id: "bot", name: "Bottom", type: "system", description: "", parentId: null },
    };
    const diagram = diagramFrom({
      components: Object.values(components),
      connections: [{ id: "e", sourceId: "top", targetId: "bot", label: "x" } as Connection],
      layouts: [
        { elementId: "top", x: 100, y: 0, width: 200, height: 80 },
        { elementId: "bot", x: 100, y: 300, width: 200, height: 80 },
      ],
      skipped: [],
    });
    // The reading direction picks the sides: top-to-bottom leaves from the bottom edge.
    const xml = exportDrawio({ ...diagram, direction: "TB" }, {});
    expect(xml).toMatch(/exitY="1"/);
    expect(xml).toMatch(/entryY="0"/);
  });

  it("container fixture: every anchor fraction stays within [0, 1]", () => {
    const xml = fixture("drawio/containers-relative.drawio");
    const fractions = [...xml.matchAll(/(?:exit|entry)[XY]="([^"]+)"/g)].map((m) => Number(m[1]));
    expect(fractions.length).toBeGreaterThan(0);
    for (const f of fractions) {
      expect(f).toBeGreaterThanOrEqual(0);
      expect(f).toBeLessThanOrEqual(1);
    }
  });
});
